// Builds web versions of the original photos in ./photos and a manifest the website reads.
//
//   npm run photos            process new/changed photos
//   npm run photos -- --clean rebuild everything
//
// Folder rules (./photos/<folder>/<name>.<jpg|jpeg|png|webp|avif>):
//   <menu-section>/<dish-id>.jpg   → photo for that dish (e.g. ramen/miso-ramen.jpg)
//   restaurant/storefront.jpg, restaurant/interior.jpg, … → places
//   instagram/*, catering/*, branding/* → gallery / site imagery
// Output: client/public/photos/<folder>/<name>-<width>.webp (640/1280/1920/3840, never upscaled)
//         client/src/data/photos.generated.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'photos');
const CUT_SRC = path.join(ROOT, 'cutouts');
const CUT_OUT = path.join(ROOT, 'client', 'public', 'cutouts');
const OUT = path.join(ROOT, 'client', 'public', 'photos');
const MANIFEST = path.join(ROOT, 'client', 'src', 'data', 'photos.generated.json');
const WIDTHS = [640, 1280, 1920, 3840];
const QUALITY = { 640: 78, 1280: 78, 1920: 76, 3840: 72 };
const IMG = /\.(jpe?g|png|webp|avif|tiff?)$/i;
const clean = process.argv.includes('--clean');

const menu = JSON.parse(fs.readFileSync(path.join(ROOT, 'server', 'src', 'data', 'menu.json'), 'utf8'));
const dishById = new Map(menu.categories.flatMap((c) => c.items.map((i) => [i.id, { ...i, category: c.slug }])));
const sources = fs.existsSync(path.join(SRC, 'sources.json'))
  ? new Map(JSON.parse(fs.readFileSync(path.join(SRC, 'sources.json'), 'utf8')).photos.map((p) => [p.file, p]))
  : new Map();

if (clean && fs.existsSync(OUT)) fs.rmSync(OUT, { recursive: true, force: true });
if (clean && fs.existsSync(CUT_OUT)) fs.rmSync(CUT_OUT, { recursive: true, force: true });

const files = [];
for (const folder of fs.readdirSync(SRC, { withFileTypes: true })) {
  if (!folder.isDirectory() || folder.name.startsWith('.') || folder.name === 'unsorted') continue;
  for (const f of fs.readdirSync(path.join(SRC, folder.name))) {
    if (IMG.test(f)) files.push({ folder: folder.name, file: f, stem: path.parse(f).name.toLowerCase() });
  }
}

const toHex = ({ r, g, b }) => `#${[r, g, b].map((v) => Math.round(v).toString(16).padStart(2, '0')).join('')}`;
const manifest = { generated: new Date().toISOString(), note: 'Generated by tools/photos.mjs — do not edit by hand.', dishes: {}, places: {}, instagram: [], branding: {} };
let made = 0;
let skipped = 0;

async function processOne({ folder, file, stem }) {
  const input = path.join(SRC, folder, file);
  const outDir = path.join(OUT, folder);
  fs.mkdirSync(outDir, { recursive: true });
  const img = sharp(input, { failOn: 'none' }).rotate();
  const meta = await img.metadata();
  const origW = meta.autoOrient?.width ?? meta.width;
  const origH = meta.autoOrient?.height ?? meta.height;
  const widths = WIDTHS.filter((w) => w <= origW);
  if (!widths.length) widths.push(origW);
  const srcTime = fs.statSync(input).mtimeMs;
  for (const w of widths) {
    const out = path.join(outDir, `${stem}-${w}.webp`);
    if (fs.existsSync(out) && fs.statSync(out).mtimeMs >= srcTime) {
      skipped += 1;
      continue;
    }
    await sharp(input, { failOn: 'none' })
      .rotate()
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: QUALITY[w] ?? 76, effort: 5, smartSubsample: true })
      .toFile(out);
    made += 1;
  }
  const { dominant } = await sharp(input, { failOn: 'none' }).resize(64).stats();
  const url = (w) => `/photos/${folder}/${stem}-${w}.webp`;
  const mid = widths.includes(1280) ? 1280 : widths[widths.length - 1];
  const src = sources.get(`${folder}/${file}`);
  const entry = {
    src: url(mid),
    srcset: widths.map((w) => `${url(w)} ${w}w`).join(', '),
    largest: url(widths[widths.length - 1]),
    width: origW,
    height: origH,
    color: toHex(dominant),
    folder,
  };
  const dish = dishById.get(stem);
  if (dish && dish.category === folder) {
    manifest.dishes[stem] = { ...entry, alt: `${dish.name} at Fuji Japanese Restaurant`, source: src?.source ?? 'photos folder', ...(src?.illustrative ? { illustrative: true } : {}) };
  } else if (folder === 'instagram') {
    manifest.instagram.push({ ...entry, id: stem, alt: src?.altOnSource || 'Fuji Japanese Restaurant on Instagram' });
  } else if (folder === 'branding') {
    manifest.branding[stem] = { ...entry, alt: src?.altOnSource || 'Fuji Japanese Restaurant logo' };
  } else {
    if (dish) console.warn(`  note: ${folder}/${file} is a dish id but sits in "${folder}" (expected "${dish.category}") — treated as a place photo`);
    manifest.places[stem] = { ...entry, alt: (src?.altOnSource || stem.replace(/-/g, ' ')).replace(/\s+/g, ' ').trim(), source: src?.source ?? 'photos folder' };
  }
}

const started = Date.now();
const queue = [...files];
await Promise.all(
  Array.from({ length: 4 }, async () => {
    while (queue.length) {
      const job = queue.shift();
      try {
        await processOne(job);
      } catch (err) {
        console.error(`  ✗ ${job.folder}/${job.file}: ${err.message}`);
      }
    }
  }),
);
/* Cut-outs (transparent PNGs from tools/cutout.py) → transparent WebP, attached to their dish */
let cutouts = 0;
if (fs.existsSync(CUT_SRC)) {
  const cutJobs = [];
  for (const folder of fs.readdirSync(CUT_SRC, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    for (const f of fs.readdirSync(path.join(CUT_SRC, folder.name))) {
      if (/\.png$/i.test(f)) cutJobs.push({ folder: folder.name, file: f, stem: path.parse(f).name.toLowerCase() });
    }
  }
  const cutQueue = [...cutJobs];
  await Promise.all(
    Array.from({ length: 4 }, async () => {
      while (cutQueue.length) {
        const { folder, file, stem } = cutQueue.shift();
        if (!manifest.dishes[stem]) continue;
        try {
          const input = path.join(CUT_SRC, folder, file);
          const meta = await sharp(input).metadata();
          const widths = WIDTHS.filter((w) => w <= meta.width);
          if (!widths.length) widths.push(meta.width);
          fs.mkdirSync(path.join(CUT_OUT, folder), { recursive: true });
          const srcTime = fs.statSync(input).mtimeMs;
          for (const w of widths) {
            const out = path.join(CUT_OUT, folder, `${stem}-${w}.webp`);
            if (fs.existsSync(out) && fs.statSync(out).mtimeMs >= srcTime) {
              skipped += 1;
              continue;
            }
            await sharp(input).resize({ width: w, withoutEnlargement: true }).webp({ quality: QUALITY[w] ?? 76, alphaQuality: 90, effort: 5 }).toFile(out);
            made += 1;
          }
          const url = (w) => `/cutouts/${folder}/${stem}-${w}.webp`;
          const mid = widths.includes(1280) ? 1280 : widths[widths.length - 1];
          manifest.dishes[stem].cutout = {
            src: url(mid),
            srcset: widths.map((w) => `${url(w)} ${w}w`).join(', '),
            largest: url(widths[widths.length - 1]),
            width: meta.width,
            height: meta.height,
          };
          cutouts += 1;
        } catch (err) {
          console.error(`  ✗ cutout ${folder}/${file}: ${err.message}`);
        }
      }
    }),
  );
}

manifest.instagram.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
fs.writeFileSync(MANIFEST, `${JSON.stringify(manifest, null, 1)}\n`);

const dishes = Object.keys(manifest.dishes).length;
const missing = [...dishById.keys()].filter((id) => !manifest.dishes[id]);
console.log(`photos: ${files.length} originals → ${made} new web images (${skipped} up to date) in ${((Date.now() - started) / 1000).toFixed(1)} s`);
console.log(`cut-outs (food on black): ${cutouts}`);
console.log(`dishes with a real photo: ${dishes}/${dishById.size}; places: ${Object.keys(manifest.places).join(', ') || 'none'}; instagram: ${manifest.instagram.length}`);
if (missing.length) console.log(`dishes still using illustrations (${missing.length}): ${missing.join(', ')}`);
